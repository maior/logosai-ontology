const LanguageContext = createContext({ lang: "en", setLang: () => {}, t: (k) => k });

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState("en");

  useEffect(() => {
    // localStorage 우선 → 브라우저 언어 감지 → en 폴백
    const saved = typeof window !== "undefined" ? localStorage.getItem("ontology_lang") : null;
    if (saved === "ko" || saved === "en") {
      setLangState(saved);
    } else if (typeof navigator !== "undefined" && navigator.language?.startsWith("ko")) {
      setLangState("ko");
    }
  }, []);

  const setLang = (next) => {
    setLangState(next);
    if (typeof window !== "undefined") localStorage.setItem("ontology_lang", next);
  };

  const t = (key, vars) => {
    let s = (DICT[lang] && DICT[lang][key]) ?? DICT.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useT() {
  return useContext(LanguageContext);
}
